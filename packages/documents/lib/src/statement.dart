          children: <pw.Widget>[
            pw.Text(
              'PREPARED FOR',
              style: const pw.TextStyle(
                fontSize: 7,
                color: muted,
                letterSpacing: 1,
              ),
            ),
            pw.SizedBox(height: 3),
            pw.Text(
              asciiText(statement.customerCompany ?? statement.customerName),
              style: const pw.TextStyle(
                fontSize: 11,
