pw.Widget _table(StatementDocument statement) {
  return pw.TableHelper.fromTextArray(
    headers: <String>[
      'Date',
      'Reference',
      'Description',
      'Amount',
      'Paid',
      'Balance',
    ],
    data: <List<String>>[
      for (final line in statement.lines)
        <String>[
          _date(line.date),
          asciiText(line.reference),
          asciiText(line.description),
          Fils(line.amountFils).aedText,
          Fils(line.paidFils).aedText,
          Fils(line.balanceFils).aedText,
        ],
    ],
    headerStyle: const pw.TextStyle(
      fontSize: 8,
      color: PdfColors.white,
      fontWeight: pw.FontWeight.bold,
    ),
    headerDecoration: const pw.BoxDecoration(color: brandPetrol),
    cellStyle: const pw.TextStyle(fontSize: 8.5),
    cellPadding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 6),
    columnWidths: <int, pw.TableColumnWidth>{
      0: const pw.FlexColumnWidth(1.5),
      1: const pw.FlexColumnWidth(2.4),
      2: const pw.FlexColumnWidth(3.0),
      3: const pw.FlexColumnWidth(1.5),
      4: const pw.FlexColumnWidth(1.5),
      5: const pw.FlexColumnWidth(1.6),
    },
    cellAlignments: <int, pw.Alignment>{
      0: pw.Alignment.centerLeft,
      1: pw.Alignment.centerLeft,
      2: pw.Alignment.centerLeft,
      3: pw.Alignment.centerRight,
      4: pw.Alignment.centerRight,
      5: pw.Alignment.centerRight,
    },
    border: const pw.TableBorder(
      horizontalInside: pw.BorderSide(color: ruleLine, width: 0.5),
      bottom: pw.BorderSide(color: ruleLine, width: 0.5),
    ),
  );
}

pw.Widget _summary(StatementDocument statement) {
  pw.Widget row(String label, String value, {bool bold = false}) {
    return pw.Padding(
      padding: const pw.EdgeInsets.symmetric(vertical: 2),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: <pw.Widget>[
          pw.Text(
            label,
            style: pw.TextStyle(
              fontSize: bold ? 11 : 9,
              fontWeight: bold ? pw.FontWeight.bold : pw.FontWeight.normal,
            ),
          ),
          pw.Text(
            value,
            style: pw.TextStyle(
              fontSize: bold ? 11 : 9,
              fontWeight: bold ? pw.FontWeight.bold : pw.FontWeight.normal,
            ),
          ),
        ],
      ),
    );
  }

  return pw.Row(
    mainAxisAlignment: pw.MainAxisAlignment.end,
    children: <pw.Widget>[
      pw.SizedBox(
        width: 240,
        child: pw.Column(
          children: <pw.Widget>[
            if (statement.openingBalanceFils != 0)
              row(
                'Opening balance',
                Fils(statement.openingBalanceFils).aedText,
              ),
            pw.Divider(height: 6, color: ruleLine),
            row(
              'Closing balance',
              Fils(statement.closingBalanceFils).aedText,
              bold: true,
            ),
          ],
        ),
      ),
    ],
  );
}

pw.Widget _footnote(CompanyProfile company) {
  return pw.Text(
    asciiText(
      'This statement summarises the invoices on file with ${company.name}. '
      'Please quote the invoice number with any payment or query.',
    ),
    style: const pw.TextStyle(fontSize: 8, color: muted),
  );
}

String _date(DateTime value) {
  final local = value.toLocal();
  const months = <String>[
    'Jan',
    'Feb',
    'Mar',
    'Apr',
    'May',
    'Jun',
    'Jul',
    'Aug',
    'Sep',
    'Oct',
    'Nov',
    'Dec',
  ];
  return '${local.day} ${months[local.month - 1]} ${local.year}';
}
