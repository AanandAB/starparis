/// The statement of account a customer receives.
///
/// A statement is a view over bills that already exist, so it lists each
/// invoice with what was charged and what was paid, and carries the running
/// balance. The numbers are the same ones on the customer's screen — nothing is
/// looked up fresh — so a counter conversation can end with paper that agrees
/// with the screen.
library;

import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:starparis_domain/starparis_domain.dart';

import 'models.dart';
import 'style.dart';

Future<Uint8List> buildStatementPdf(
  StatementDocument statement,
  CompanyProfile company, {
  bool compress = true,
}) async {
  final document = pw.Document(
    title: 'Statement of account ${statement.customerName}',
    author: company.name,
    creator: 'Star Paris',
    compress: compress,
  );

  document.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.fromLTRB(36, 32, 36, 40),
      header: (context) => _header(company),
      footer: _footer,
      build: (context) => <pw.Widget>[
        _titleRow(statement),
        pw.SizedBox(height: 16),
        _parties(statement, company),
        pw.SizedBox(height: 16),
        _table(statement),
        pw.SizedBox(height: 10),
        _summary(statement),
        pw.SizedBox(height: 14),
        _footnote(company),
      ],
    ),
  );

  return document.save();
}

pw.Widget _header(CompanyProfile company) {
  return pw.Column(
    crossAxisAlignment: pw.CrossAxisAlignment.start,
    children: <pw.Widget>[
      pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: <pw.Widget>[
          pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: <pw.Widget>[
              pw.Text(
                asciiText(company.name),
                style: const pw.TextStyle(
                  fontSize: 17,
                  fontWeight: pw.FontWeight.bold,
                  color: brandPetrol,
                ),
              ),
              if (company.branchName != null)
                pw.Text(
                  asciiText(company.branchName!),
                  style: const pw.TextStyle(fontSize: 9, color: muted),
                ),
              pw.SizedBox(height: 3),
              pw.Text(
                asciiText(company.address),
                style: const pw.TextStyle(fontSize: 8, color: muted),
              ),
              pw.Text(
                asciiText(
                  'Tel ${company.phone}'
                  '${company.email == null ? '' : '  |  ${company.email}'}',
                ),
                style: const pw.TextStyle(fontSize: 8, color: muted),
              ),
              pw.SizedBox(height: 3),
              pw.Text(
                asciiText('TRN ${company.trn}'),
                style: const pw.TextStyle(
                  fontSize: 8,
                  fontWeight: pw.FontWeight.bold,
                ),
              ),
            ],
          ),
          pw.Container(
            padding: const pw.EdgeInsets.symmetric(horizontal: 10, vertical: 6),
            decoration: const pw.BoxDecoration(color: brandPetrol),
            child: pw.Text(
              'STATEMENT',
              style: const pw.TextStyle(
                fontSize: 10,
                fontWeight: pw.FontWeight.bold,
                color: PdfColors.white,
                letterSpacing: 1.5,
              ),
            ),
          ),
        ],
      ),
      pw.SizedBox(height: 10),
      pw.Container(height: 2, color: brandSand),
    ],
  );
}

pw.Widget _footer(pw.Context context) {
  return pw.Row(
    mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
    children: <pw.Widget>[
      pw.Text(
        'Generated by Star Paris | statement of account is not a tax invoice',
        style: const pw.TextStyle(fontSize: 7, color: muted),
      ),
      pw.Text(
        'Page ${context.pageNumber} of ${context.pagesCount}',
        style: const pw.TextStyle(fontSize: 7, color: muted),
      ),
    ],
  );
}

pw.Widget _titleRow(StatementDocument statement) {
  return pw.Row(
    mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
    crossAxisAlignment: pw.CrossAxisAlignment.end,
    children: <pw.Widget>[
      pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: <pw.Widget>[
          pw.Text(
            'STATEMENT OF ACCOUNT',
            style: const pw.TextStyle(
              fontSize: 20,
              fontWeight: pw.FontWeight.bold,
              color: brandPetrol,
            ),
          ),
          pw.Text(
            asciiText(statement.customerName),
            style: const pw.TextStyle(fontSize: 11),
          ),
        ],
      ),
      pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.end,
        children: <pw.Widget>[
          _metaLine('Generated', _date(statement.generatedAt)),
          if (statement.periodLabel.isNotEmpty)
            _metaLine('Period', asciiText(statement.periodLabel)),
        ],
      ),
    ],
  );
}

pw.Widget _metaLine(String label, String value) {
  return pw.Row(
    children: <pw.Widget>[
      pw.Text('$label  ', style: const pw.TextStyle(fontSize: 8, color: muted)),
      pw.Text(value, style: const pw.TextStyle(fontSize: 9)),
    ],
  );
}

