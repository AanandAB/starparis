/// The quotation a customer receives.
///
/// Content, in the order a customer reads it: who is quoting, what for, how
/// much, what it includes, and when the price expires. Every number comes from
/// the stored order line, never recomputed — a quote printed on Monday must
/// still say the same thing on Friday after the price book moved.
library;

import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:starparis_domain/starparis_domain.dart';

import 'models.dart';
import 'style.dart';

Future<Uint8List> buildQuotePdf(
  QuoteDocument quote,
  CompanyProfile company, {
  bool compress = true,
}) async {
  final document = pw.Document(
    title: 'Quotation ${quote.number}',
    author: company.name,
    creator: 'Star Paris',
    compress: compress,
  );

  document.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.fromLTRB(36, 32, 36, 40),
      header: (context) => _header(company),
      footer: _footer,
      build: (context) => <pw.Widget>[
        _titleRow(quote),
        pw.SizedBox(height: 18),
        _parties(quote),
        pw.SizedBox(height: 18),
        _items(quote),
        pw.SizedBox(height: 10),
        _totals(quote),
        if (quote.notes.trim().isNotEmpty) ...<pw.Widget>[
          pw.SizedBox(height: 16),
          pw.Text('Notes', style: _labelStyle),
          pw.SizedBox(height: 4),
          pw.Text(
            asciiText(quote.notes.trim()),
            style: const pw.TextStyle(fontSize: 9),
          ),
        ],
        pw.SizedBox(height: 18),
        pw.Container(
          padding: const pw.EdgeInsets.all(10),
          decoration: const pw.BoxDecoration(
            color: PdfColor.fromInt(0xFFF7F4EE),
            borderRadius: pw.BorderRadius.all(pw.Radius.circular(4)),
          ),
          child: pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: <pw.Widget>[
              pw.Text('Terms', style: _labelStyle),
              pw.SizedBox(height: 3),
              pw.Text(
                asciiText(quote.terms),
                style: const pw.TextStyle(fontSize: 8, color: muted),
              ),
            ],
          ),
        ),
        pw.SizedBox(height: 26),
        _signatureRow(),
      ],
    ),
  );

  return document.save();
}

const pw.TextStyle _labelStyle = pw.TextStyle(
  fontSize: 9,
  fontWeight: pw.FontWeight.bold,
  color: ink,
);

pw.Widget _header(CompanyProfile company) {
  return pw.Column(
    crossAxisAlignment: pw.CrossAxisAlignment.start,
    children: <pw.Widget>[
      pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: <pw.Widget>[
          pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: <pw.Widget>[
              pw.Text(
                asciiText(company.name),
                style: const pw.TextStyle(
                  fontSize: 17,
                  fontWeight: pw.FontWeight.bold,
                  color: brandPetrol,
                ),
              ),
              if (company.branchName != null)
                pw.Text(
                  asciiText(company.branchName!),
                  style: const pw.TextStyle(fontSize: 9, color: muted),
                ),
              pw.SizedBox(height: 3),
              pw.Text(
                asciiText(company.address),
                style: const pw.TextStyle(fontSize: 8, color: muted),
              ),
              pw.Text(
                asciiText(
                  'Tel ${company.phone}'
                  '${company.email == null ? '' : '  |  ${company.email}'}',
                ),
                style: const pw.TextStyle(fontSize: 8, color: muted),
              ),
              pw.SizedBox(height: 3),
              pw.Text(
                asciiText('TRN ${company.trn}'),
                style: const pw.TextStyle(
                  fontSize: 8,
                  fontWeight: pw.FontWeight.bold,
                ),
              ),
            ],
          ),
          pw.Container(
            padding: const pw.EdgeInsets.symmetric(horizontal: 10, vertical: 6),
            decoration: const pw.BoxDecoration(color: brandPetrol),
            child: pw.Text(
              'QUOTATION',
              style: const pw.TextStyle(
                fontSize: 10,
                fontWeight: pw.FontWeight.bold,
                color: PdfColors.white,
                letterSpacing: 1.5,
              ),
            ),
          ),
        ],
      ),
      pw.SizedBox(height: 10),
      pw.Container(height: 2, color: brandSand),
    ],
  );
}

pw.Widget _footer(pw.Context context) {
  return pw.Row(
    mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
    children: <pw.Widget>[
      pw.Text(
        'Generated by Star Paris | this quotation is not a tax invoice',
        style: const pw.TextStyle(fontSize: 7, color: muted),
      ),
      pw.Text(
        'Page ${context.pageNumber} of ${context.pagesCount}',
        style: const pw.TextStyle(fontSize: 7, color: muted),
      ),
    ],
  );
}

pw.Widget _titleRow(QuoteDocument quote) {
  return pw.Row(
    mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
    crossAxisAlignment: pw.CrossAxisAlignment.end,
    children: <pw.Widget>[
      pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: <pw.Widget>[
          pw.Text(
            'Quotation',
            style: const pw.TextStyle(
              fontSize: 22,
              fontWeight: pw.FontWeight.bold,
            ),
          ),
          pw.Text(
            asciiText(quote.number),
            style: const pw.TextStyle(fontSize: 11, color: brandPetrol),
          ),
        ],
      ),
      pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.end,
        children: <pw.Widget>[
          _metaLine('Date', _date(quote.issuedAt)),
          _metaLine('Valid until', _date(quote.validUntil)),
        ],
      ),
    ],
  );
}

pw.Widget _metaLine(String label, String value) {
  return pw.Row(
    children: <pw.Widget>[
      pw.Text('$label  ', style: const pw.TextStyle(fontSize: 8, color: muted)),
      pw.Text(value, style: const pw.TextStyle(fontSize: 9)),
    ],
  );
}

pw.Widget _parties(QuoteDocument quote) {
  return pw.Row(
    crossAxisAlignment: pw.CrossAxisAlignment.start,
    children: <pw.Widget>[
      pw.Expanded(
        child: pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: <pw.Widget>[
            pw.Text(
              'QUOTATION FOR',
              style: const pw.TextStyle(
                fontSize: 7,
                color: muted,
                letterSpacing: 1,
              ),
            ),
            pw.SizedBox(height: 3),
            pw.Text(
              asciiText(quote.customerCompany ?? quote.customerName),
              style: const pw.TextStyle(
                fontSize: 11,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
            if (quote.customerCompany != null)
              pw.Text(
                asciiText(quote.customerName),
                style: const pw.TextStyle(fontSize: 9),
              ),
            if (quote.customerPhone != null)
              pw.Text(
                asciiText(quote.customerPhone!),
                style: const pw.TextStyle(fontSize: 9, color: muted),
              ),
            if (quote.customerTrn != null)
              pw.Text(
                asciiText('TRN ${quote.customerTrn}'),
                style: const pw.TextStyle(fontSize: 9, color: muted),
              ),
          ],
        ),
      ),
      pw.SizedBox(width: 24),
      pw.Expanded(
        child: pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: <pw.Widget>[
            pw.Text(
              'PREPARED BY',
              style: const pw.TextStyle(
                fontSize: 7,
                color: muted,
                letterSpacing: 1,
              ),
            ),
            pw.SizedBox(height: 3),
            pw.Text('Counter sales', style: const pw.TextStyle(fontSize: 9)),
            pw.Text(
              'Star Paris Graphic LLC',
              style: const pw.TextStyle(fontSize: 9, color: muted),
            ),
          ],
        ),
      ),
    ],
  );
}

pw.Widget _items(QuoteDocument quote) {
  return pw.TableHelper.fromTextArray(
    headers: <String>['Description', 'Qty', 'Unit (AED)', 'Amount (AED)'],
    data: <List<String>>[
      for (final line in quote.lines)
        <String>[
          asciiText(line.description),
          '${line.quantity}',
          Fils(line.unitFils).aedText,
          Fils(line.amountFils).aedText,
        ],
    ],
    headerStyle: const pw.TextStyle(
      fontSize: 8,
      color: PdfColors.white,
      fontWeight: pw.FontWeight.bold,
    ),
    headerDecoration: const pw.BoxDecoration(color: brandPetrol),
    cellStyle: const pw.TextStyle(fontSize: 8.5),
    cellPadding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 6),
    cellAlignments: <int, pw.Alignment>{
      0: pw.Alignment.centerLeft,
      1: pw.Alignment.centerRight,
      2: pw.Alignment.centerRight,
      3: pw.Alignment.centerRight,
    },
    border: const pw.TableBorder(
      horizontalInside: pw.BorderSide(color: ruleLine, width: 0.5),
      bottom: pw.BorderSide(color: ruleLine, width: 0.5),
    ),
  );
}

pw.Widget _totals(QuoteDocument quote) {
  return pw.Row(
    mainAxisAlignment: pw.MainAxisAlignment.end,
    children: <pw.Widget>[
      pw.SizedBox(
        width: 220,
        child: pw.Column(
          children: <pw.Widget>[
            _totalRow('Subtotal', Fils(quote.subtotalFils)),
            _totalRow(
              'VAT ${(quote.vatBps / 100).toStringAsFixed(0)}%',
              Fils(quote.vatFils),
            ),
            pw.Divider(height: 6, color: ruleLine),
            _totalRow('Total', Fils(quote.totalFils), emphatic: true),
          ],
        ),
      ),
    ],
  );
}

pw.Widget _totalRow(String label, Fils amount, {bool emphatic = false}) {
  return pw.Padding(
    padding: const pw.EdgeInsets.symmetric(vertical: 2),
    child: pw.Row(
      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
      children: <pw.Widget>[
        pw.Text(
          label,
          style: pw.TextStyle(
            fontSize: emphatic ? 11 : 9,
            fontWeight: emphatic ? pw.FontWeight.bold : pw.FontWeight.normal,
          ),
        ),
        pw.Text(
          'AED ${amount.aedText}',
          style: pw.TextStyle(
            fontSize: emphatic ? 11 : 9,
            fontWeight: emphatic ? pw.FontWeight.bold : pw.FontWeight.normal,
          ),
        ),
      ],
    ),
  );
}

pw.Widget _signatureRow() {
  return pw.Row(
    children: <pw.Widget>[
      pw.Expanded(child: _signatureBox('Accepted by (name, signature, date)')),
      pw.SizedBox(width: 24),
      pw.Expanded(child: _signatureBox('For Star Paris Graphic LLC')),
    ],
  );
}

pw.Widget _signatureBox(String label) {
  return pw.Column(
    crossAxisAlignment: pw.CrossAxisAlignment.start,
    children: <pw.Widget>[
      pw.Container(
        height: 28,
        decoration: const pw.BoxDecoration(
          border: pw.Border(bottom: pw.BorderSide(color: ruleLine, width: 1)),
        ),
      ),
      pw.SizedBox(height: 4),
      pw.Text(label, style: const pw.TextStyle(fontSize: 7, color: muted)),
    ],
  );
}

String _date(DateTime value) {
  final local = value.toLocal();
  const months = <String>[
    'Jan',
    'Feb',
    'Mar',
    'Apr',
    'May',
    'Jun',
    'Jul',
    'Aug',
    'Sep',
    'Oct',
    'Nov',
    'Dec',
  ];
  return '${local.day} ${months[local.month - 1]} ${local.year}';
}
