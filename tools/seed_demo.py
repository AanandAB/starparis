"""Generates the demo seed SQL for the dev database.

Why a generator rather than a checked-in .sql file: the password hash must be
PBKDF2 with the same format the Worker verifies, and checking a hash into git
means checking a password into git. This script prints SQL to stdout; pipe it
into `wrangler d1 execute --file`.

Usage:
    python tools/seed_demo.py > seeds/demo.sql
    wrangler d1 execute starparis-dev --remote --file seeds/demo.sql

The demo owner is +971500000001 / starparis-demo. Change it before anyone
outside the build sees the environment.
"""

from __future__ import annotations

import base64
import hashlib
import os
from datetime import datetime, timezone

TENANT = "0193f0b1-0000-7000-8000-000000000001"
BRANCH_SHJ = "0193f0b1-0000-7000-8000-0000000000b1"
BRANCH_DXB = "0193f0b1-0000-7000-8000-0000000000b2"
ROLE_OWNER = "0193f0b1-0000-7000-8000-0000000000c1"
ROLE_COUNTER = "0193f0b1-0000-7000-8000-0000000000c2"
USER_OWNER = "0193f0b1-0000-7000-8000-0000000000d1"
USER_COUNTER = "0193f0b1-0000-7000-8000-0000000000d2"

ITERATIONS = 100_000
PASSWORD = "starparis-demo"


def hash_password(password: str) -> str:
    salt = os.urandom(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, ITERATIONS, 32)
    return "pbkdf2$sha256${}${}${}".format(
        ITERATIONS,
        base64.b64encode(salt).decode(),
        base64.b64encode(digest).decode(),
    )


def q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def main() -> None:
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    password_hash = hash_password(PASSWORD)

    print("-- Generated by tools/seed_demo.py — development data only.")
    print(f"INSERT OR IGNORE INTO tenants (id, name, trn, created_at, updated_at)")
    print(f"  VALUES ({q(TENANT)}, 'Star Paris Graphic LLC', NULL, {q(now)}, {q(now)});")

    for branch_id, code, name in (
        (BRANCH_SHJ, "SHJ1", "Sharjah — Industrial Area"),
        (BRANCH_DXB, "DXB1", "Dubai — Deira"),
    ):
        print(
            "INSERT OR IGNORE INTO branches "
            "(id, tenant_id, code, name, created_at, updated_at) VALUES "
            f"({q(branch_id)}, {q(TENANT)}, {q(code)}, {q(name)}, {q(now)}, {q(now)});"
        )

    for role_id, key, name in (
        (ROLE_OWNER, "owner", "Owner"),
        (ROLE_COUNTER, "counter", "Sales / Counter"),
    ):
        print(
            "INSERT OR IGNORE INTO roles "
            "(id, tenant_id, role_key, name, is_system, created_at, updated_at) VALUES "
            f"({q(role_id)}, {q(TENANT)}, {q(key)}, {q(name)}, 1, {q(now)}, {q(now)});"
        )

    for user_id, branch_id, role_id, name, phone in (
        (USER_OWNER, BRANCH_SHJ, ROLE_OWNER, "Owner", "+971500000001"),
        (USER_COUNTER, BRANCH_SHJ, ROLE_COUNTER, "Counter", "+971500000002"),
    ):
        print(
            "INSERT OR IGNORE INTO users "
            "(id, tenant_id, branch_id, role_id, name, phone_e164, password_hash, "
            "created_at, updated_at) VALUES "
            f"({q(user_id)}, {q(TENANT)}, {q(branch_id)}, {q(role_id)}, {q(name)}, "
            f"{q(phone)}, {q(password_hash)}, {q(now)}, {q(now)});"
        )


if __name__ == "__main__":
    main()
